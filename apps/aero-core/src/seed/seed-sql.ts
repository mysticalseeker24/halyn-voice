import { HalynError } from '@halyn/shared';
import { getTableConfig, type SQLiteTable } from 'drizzle-orm/sqlite-core';
import { accounts, cards, fees, loans, payees, transactions } from '../db/schema';
import { DEMO_CUSTOMERS, type SeedCustomer, type SeedRows, seedRows } from './seed-data';

// Seed rows → plain SQL that `wrangler d1 execute --file` runs (seed/seed.sql) and that tests run statement by
// statement, so the file and the tests share one source. Re-running resets the customers' demo state; it never touches
// used_grants (a reset must not make an already-executed grant usable again).

const TABLE_ORDER: readonly (readonly [keyof SeedRows, SQLiteTable])[] = [
  ['accounts', accounts],
  ['cards', cards],
  ['fees', fees],
  ['loans', loans],
  ['payees', payees],
  ['transactions', transactions],
];

/** A literal for SQLite: strings quoted, safe integers, booleans as 0/1, null. Anything else fails closed. */
export function sqlValue(value: unknown): string {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'boolean') return value ? '1' : '0';
  if (typeof value === 'number') {
    if (!Number.isSafeInteger(value))
      throw new HalynError('E_FAIL_CLOSED', `seed: ${value} is not a safe integer`);
    return String(value);
  }
  if (typeof value === 'string') return `'${value.replaceAll("'", "''")}'`;
  throw new HalynError('E_FAIL_CLOSED', `seed: cannot write a ${typeof value} as SQL`);
}

function insert(table: SQLiteTable, row: Record<string, unknown>): string {
  const { name, columns } = getTableConfig(table);
  const names = columns.map((c) => c.name);
  const values = names.map((column) => sqlValue(row[column]));
  return `INSERT INTO ${name} (${names.join(', ')}) VALUES (${values.join(', ')});`;
}

/** DELETE each customer's rows (children first), then INSERT the template rows. */
export function seedStatements(customers: readonly SeedCustomer[]): string[] {
  const rows = seedRows(customers);
  const statements: string[] = [];
  for (const [, table] of [...TABLE_ORDER].reverse())
    for (const { tenant, customer } of customers)
      statements.push(
        `DELETE FROM ${getTableConfig(table).name} WHERE tenant_id = ${sqlValue(tenant)} AND customer_ref = ${sqlValue(customer)};`,
      );
  for (const [key, table] of TABLE_ORDER)
    for (const row of rows[key]) statements.push(insert(table, row as Record<string, unknown>));
  return statements;
}

/** The content of apps/aero-core/seed/seed.sql (a test keeps the committed file equal to this). */
export function buildSeedSql(customers: readonly SeedCustomer[] = DEMO_CUSTOMERS): string {
  return [
    '-- Aero Core demo seed. Generated by `pnpm seed:core` from apps/aero-core/src/seed/seed-data.ts: do not edit.',
    '-- Resets the demo customers (accounts, cards, fees, loans, payees, transactions); never touches used_grants.',
    ...seedStatements(customers),
    '',
  ].join('\n');
}
