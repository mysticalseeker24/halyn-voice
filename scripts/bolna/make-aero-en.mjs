function build(region) {
  const r = REGIONS[region];
  const agent = JSON.parse(readFileSync('agents/aero-hi.graph.json', 'utf8'));
  const cfg = agent.agent_config;
  const task = cfg.tasks[0];
  const tools = task.tools_config;
  const llm = tools.llm_agent.llm_config;

  agent.halyn = { outbound: false, ...(region === 'us' ? { web_only: true } : {}), note: r.note };
  cfg.agent_name = r.name;
  cfg.agent_welcome_message = r.welcome;
  task.task_config.check_user_online_message = 'Are you still there?';
  for (const t of tools.api_tools.tools)
    if (t.pre_call_message)
      t.pre_call_message = typeof r.preCall === 'string' ? r.preCall : r.preCall[t.name];

  if (region === 'us') {
    // No transfer (a browser call is never put through to a phone); propose_action reports the web channel and the
    // US pack's actions and dollars (the Indian list has rupees/INR, which the Gate would refuse here).
    tools.api_tools.tools = tools.api_tools.tools.filter((t) => t.name !== 'transfer_call_specialist');
    delete tools.api_tools.tools_params.transfer_call_specialist;
    tools.api_tools.tools_params.propose_action.param.channel = 'web';
    const propose = tools.api_tools.tools.find((t) => t.name === 'propose_action');
    propose.parameters.properties.action.description =
      'One of: card.freeze, balance.view, statement.view, fee.waive, transfer.saved, wire.new, profile.change_mobile, dispute.charge, account.close, wire.international.';
    propose.parameters.properties.params.description =
      'The details as key=value pairs separated by semicolons. No quotes, no braces, no JSON. Amounts are amount_minor = dollars x 100 (8000 dollars -> 800000) with currency USD. Keys per action: card.freeze card_last4; balance.view/statement.view/account.close account (checking); fee.waive amount_minor, currency, fee_id; transfer.saved amount_minor, currency, payee_id; wire.new amount_minor, currency, payee_account_last4, routing_last4; profile.change_mobile new_number with +1; dispute.charge card_last4, amount_minor, currency, merchant; wire.international amount_minor, currency, payee_account_last4, swift_bic, payee_country. Example: amount_minor=800000; currency=USD; payee_account_last4=3310; routing_last4=0021';
  }

  llm.agent_information = r.info.join('\n');
  llm.nodes = llm.nodes
    .filter((n) => region === 'in' || n.id !== 'transfer')
    .map((n) => {
      const node = { ...n };
      if (r.prompts[n.id]) node.prompt = r.prompts[n.id];
      if (r.statics[n.id]) {
        // A fixed line: the LLM on `confirmed` said "under review" after `done` (call ecad8cfe, 2026-10-30).
        node.node_type = 'static';
        node.static_message = r.statics[n.id];
        delete node.prompt;
      }
      if (region === 'us') {
        node.edges = (n.edges ?? []).filter((e) => e.to_node_id !== 'transfer');
        if (n.id === 'protect')
          node.edges = [
            { to_node_id: 'understand', condition: 'The caller has another request' },
            { to_node_id: 'goodbye', condition: 'The caller has nothing else or says goodbye' },
          ];
      }
      return node;
    });
  llm.routing_instructions = `You are the routing system for Aero Bank's ${region === 'us' ? 'US ' : ''}voice assistant. Pick the transition whose condition matches the caller's latest words. If none matches, stay on the current node.`;

  tools.transcriber = { ...tools.transcriber, language: 'en', ...r.transcriber };
  if (region === 'in') {
    // Same Sarvam voice (Simran, banking), speaking English.
    tools.synthesizer.provider_config.language = 'en';
  } else {
    tools.synthesizer = {
      provider: 'deepgram',
      stream: true,
      caching: true,
      buffer_size: 200,
      audio_format: 'wav',
      provider_config: { voice: 'Asteria', voice_id: 'asteria-en', model: 'aura-2' },
    };
  }
  agent.agent_prompts.task_1.system_prompt =
    "You are Aero Bank's AI voice assistant. You never complete an action yourself; you submit it for a security decision. Never ask for or read out a one-time code, PIN, password, CVV or full card or account number. Speak English.";

  writeFileSync(r.out, JSON.stringify(agent, null, 2) + '\n');
  const names = (list) => list.map((x) => x.id ?? x.name).join(', ');
  console.log(`${r.out}: ${names(llm.nodes)}; tools: ${names(tools.api_tools.tools)}`);
}

const arg = process.argv[2];
for (const region of arg ? [arg] : ['in', 'us']) {
  if (!REGIONS[region]) throw new Error(`unknown region ${region} (in|us)`);
  build(region);
}
