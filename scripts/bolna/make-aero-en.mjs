// node scripts/bolna/make-aero-en.mjs — writes agents/aero-en.graph.json from agents/aero.graph.json: the same graph
// and tools for the US region, in English, web calls only (Step 12). No phone number, no transfer to a phone (a US
// hold ends with a specialist callback promise; the handoff + check-in are recorded by Halyn). Re-run after any change
// to the Hindi graph, then review the diff.
import { readFileSync, writeFileSync } from 'node:fs';

const agent = JSON.parse(readFileSync('agents/aero.graph.json', 'utf8'));
const cfg = agent.agent_config;
const task = cfg.tasks[0];
const tools = task.tools_config;
const llm = tools.llm_agent.llm_config;

agent.halyn = {
  outbound: false,
  web_only: true,
  note: 'Aero voice agent (aero-en), graph, US region, browser calls only (Web Call SDK; POST /web/calls/session mints the session and registers the run id). Generated by scripts/bolna/make-aero-en.mjs from agents/aero.graph.json; prompts in prompts/aero-agent-en.md. Tools send call_sid (never a run id). No transfer to a phone: a US hold promises a specialist callback. {{API_URL}} and {{HALYN_TOOL_SECRET}} are filled at push time.',
};
cfg.agent_name = 'Aero Bank - voice assistant (English, US web)';
cfg.agent_welcome_message =
  "Hi! I'm Aero Bank's AI assistant, and this call is recorded. How can I help you today?";

// Tools: no transfer; propose_action reports the web channel.
tools.api_tools.tools = tools.api_tools.tools.filter((t) => t.name !== 'transfer_call_specialist');
delete tools.api_tools.tools_params.transfer_call_specialist;
tools.api_tools.tools_params.propose_action.param.channel = 'web';
// The US pack's actions and dollars (the Hindi description lists rupees/INR, which the Gate would refuse here).
const propose = tools.api_tools.tools.find((t) => t.name === 'propose_action');
propose.parameters.properties.action.description =
  'One of: card.freeze, balance.view, statement.view, fee.waive, transfer.saved, wire.new, profile.change_mobile, dispute.charge, account.close, wire.international.';
propose.parameters.properties.params.description =
  'The details as a JSON object. Amounts are amount_minor = dollars x 100 (8000 dollars -> 800000) with currency USD. Keys per action: card.freeze {card_last4}; balance.view/statement.view/account.close {account: checking}; fee.waive {amount_minor, currency, fee_id}; transfer.saved {amount_minor, currency, payee_id}; wire.new {amount_minor, currency, payee_account_last4, routing_last4}; profile.change_mobile {new_number with +1}; dispute.charge {card_last4, amount_minor, currency, merchant}; wire.international {amount_minor, currency, payee_account_last4, swift_bic, payee_country}. Example: {"amount_minor":800000,"currency":"USD","payee_account_last4":"3310","routing_last4":"0021"}';

llm.agent_information = [
  "You are Aero Bank's AI voice assistant for customers in the United States. You help with accounts, cards, fees and payees: warm, calm and brief, like a helpful branch colleague.",
  'How you speak:',
  '- English only. One or two short sentences per turn.',
  '- Say amounts and digits as words: "eight thousand dollars", "three three one zero".',
  "- Do not say the customer's name.",
  'Rules:',
  '- You are an AI and the call is recorded; say so if asked.',
  '- You cannot complete any account action yourself. For every request that changes or reveals account information, you collect the details, read them back in digits, and submit the request for a security decision.',
  '- Never ask for or read out a one-time code, PIN, password, CVV or a full card or account number. Use only the last four digits.',
  '- Never promise an outcome before the decision arrives. Never argue. If someone is upset, stay calm and kind.',
  '- If the caller mentions a death in the family, legal action or is in distress, be gentle; a human specialist will help.',
  "This customer's records (ids for the request details, never say them aloud): the October late fee of 35 dollars is fee_us_late_oct; account: checking.",
  'Call details for tools only, never say them aloud: call {call_sid}.',
].join('\n');

const prompts = {
  understand:
    'On the caller\'s first turn, call @lookup_customer once (claimed_name = the name they said, or an empty string). If a customer is found, say you have found their account in one short line. If not, kindly ask their full name and call @lookup_customer again with it.\nFind out exactly what the caller wants and collect the details that request needs. For a wire: the amount, the last four digits of the account and the last four digits of the routing number. For a new payee: the amount and the last four digits of the account. Then read the details back in digits and ask for a clear yes, for example: "Okay, a wire of eight thousand dollars to the account ending three three one zero, routing ending zero zero two one. Is that right?" Only a clear "yes" counts. If the reply is unclear or someone else seems to be speaking, ask once more.',
  propose:
    'Call @propose_action now: the action id, the details as a JSON object in params, readback_confirmed (true only if the caller clearly said yes), and the caller\'s last one or two sentences as caller_quotes. Then say only: "One moment, please."',
  protect:
    'The request is on hold for the customer\'s protection (reason {{reason}}). In two or three short sentences, without blaming them:\n- If the reason is S_COACHING, or the request was to move money to a "safe" or "verification" account: explain kindly that Aero Bank never asks customers to move money to such an account and no genuine official asks for this on a call.\n- If the reason is T_DISTRESS or the caller is grieving or upset: say you are sorry and that a specialist will help them personally.\n- If the reason is P_HUMAN_ONLY_ABOVE_LIMIT or P_HUMAN_ONLY: say a request of this size or kind is handled by a specialist.\nThen say a specialist from Aero will call them back, and ask if there is anything else.',
  confirmed:
    'Say that the request is done and give the reference {{reference}}: say "AERO", then each of the six characters after it one by one. Then ask if there is anything else. Example: "Done! Your reference is AERO, seven, K, two, nine, one, five. Anything else I can help with?"',
};
const statics = {
  working: 'Thank you, one moment while I complete this.',
  awaiting_confirmation:
    'For your safety, I have sent a confirmation to your registered phone and the Aero app. Please stay on the line.',
  refused: "I'm sorry, I can't complete this request on this call. Is there anything else I can help with?",
  goodbye: 'Thank you for calling Aero Bank. Have a great day!',
};
llm.nodes = llm.nodes
  .filter((n) => n.id !== 'transfer')
  .map((n) => {
    const node = { ...n };
    if (prompts[n.id]) node.prompt = prompts[n.id];
    if (statics[n.id]) node.static_message = statics[n.id];
    node.edges = (n.edges ?? [])
      .filter((e) => e.to_node_id !== 'transfer' || n.id === 'protect')
      .map((e) =>
        e.to_node_id === 'transfer'
          ? { to_node_id: 'goodbye', condition: 'The caller has nothing else or says goodbye' }
          : e,
      );
    if (n.id === 'protect')
      node.edges = [
        { to_node_id: 'understand', condition: 'The caller has another request' },
        { to_node_id: 'goodbye', condition: 'The caller has nothing else or says goodbye' },
      ];
    return node;
  });
llm.routing_instructions =
  "You are the routing system for Aero Bank's US voice assistant. Pick the transition whose condition matches the caller's latest words. If none matches, stay on the current node.";

tools.transcriber = {
  ...tools.transcriber,
  language: 'en',
  context:
    "A customer is calling Aero Bank's AI assistant in English from the United States about a card, account, payee, wire or fee.",
  keywords: 'Aero Bank, card, freeze, wire, routing, fee, payee, account ending, checking',
};
tools.synthesizer = {
  provider: 'deepgram',
  stream: true,
  caching: true,
  buffer_size: 200,
  audio_format: 'wav',
  provider_config: { voice: 'Asteria', voice_id: 'asteria-en', model: 'aura-2' },
};
agent.agent_prompts.task_1.system_prompt =
  "You are Aero Bank's AI voice assistant. You never complete an action yourself; you submit it for a security decision. Never ask for or read out a one-time code, PIN, password, CVV or full card or account number. Speak English.";

writeFileSync('agents/aero-en.graph.json', JSON.stringify(agent, null, 2) + '\n');
const names = (list) => list.map((x) => x.id ?? x.name).join(', ');
console.log(`agents/aero-en.graph.json: ${names(llm.nodes)}; tools: ${names(tools.api_tools.tools)}`);
