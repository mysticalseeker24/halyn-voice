// node scripts/bolna/make-test-personas.mjs — writes agents/test-*.json, the three benign test-caller personas of
// prompts/personas/README.md (Step 15, Halyn Test voice mode). Each is a simple agent built from agents/assistant.json's
// speech settings: outbound from number B to Aero's number A, call_terminate 120, guardrails 09–21, no tools, the
// Halyn webhook so Halyn sees the execution. Creating them on Bolna and every call need Saksham's go-ahead; the Test
// page's voice button stays disabled until their ids are in .env (TEST_AGENT_*_ID). Normal customers only — no
// attacker personas (docs/STATE.md: not approved). Re-run after changing a persona, then review the diff.
import { readFileSync, writeFileSync } from 'node:fs';

const base = JSON.parse(readFileSync('agents/assistant.json', 'utf8'));

// The customer the personas play; voices say the name in Devanagari (CLAUDE.md §8).
const CUSTOMER = 'सक्षम मिश्रा';

const PERSONAS = [
  {
    id: 'test-polite-hindi',
    name: 'Halyn test caller - polite Hindi',
    language: 'hi',
    speak: 'Hindi (Devanagari script)',
    behaviour: 'Calm and clear; answers each question once, politely.',
    task: 'Your debit card is lost. Ask Aero to freeze it.',
    welcome: 'नमस्ते, मैं एक AI टेस्ट कॉलर हूँ, Aero Bank की टीम के लिए जाँच कर रहा हूँ। यह call record हो रही है।',
  },
  {
    id: 'test-hinglish-noisy',
    name: 'Halyn test caller - Hinglish, noisy room',
    language: 'hi',
    speak: 'Hinglish (Hindi and English mixed, Devanagari for Hindi words)',
    behaviour: 'Sometimes starts talking before the assistant finishes; says there is noise in the room.',
    task: 'Ask when your next EMI is due, then ask to move that EMI date by five days.',
    welcome: 'हैलो, मैं एक AI टेस्ट कॉलर हूँ, Aero Bank की टीम के लिए। यह call record हो रही है।',
  },
  {
    id: 'test-impatient-en',
    name: 'Halyn test caller - impatient English',
    language: 'en',
    speak: 'English',
    behaviour: 'Short answers; repeats the request once if the assistant is slow; never rude.',
    task: 'Ask Aero to waive the 600 rupee late fee on your card.',
    welcome: "Hi, I'm an AI test caller checking Aero Bank's assistant for its team. This call is recorded.",
  },
];

const prompt = (p) =>
  [
    `You are a test caller helping Aero Bank's team check its AI assistant. You play a customer named ${CUSTOMER}.`,
    `Your goal: ${p.task} Behaviour: ${p.behaviour} Speak ${p.speak}. Be realistic and polite.`,
    'Never share a full card or account number, a PIN, a password or a one-time code; if asked, say you do not have it on you.',
    'If the assistant asks you to confirm in the app or on another call, say you will do it later. End the call when the goal is done or the assistant says it cannot help.',
  ].join('\n');

for (const p of PERSONAS) {
  const agent = JSON.parse(JSON.stringify(base));
  const cfg = agent.agent_config;
  const task = cfg.tasks[0];
  const tools = task.tools_config;
  agent.halyn = {
    outbound: true,
    test_persona: p.id,
    note: `Halyn Test voice persona ${p.id} (prompts/personas/README.md): a normal customer calling Aero's number A from number B. Generated by scripts/bolna/make-test-personas.mjs from agents/assistant.json. No tools. {{API_URL}} and {{HALYN_TOOL_SECRET}} are filled at push time.`,
  };
  cfg.agent_name = p.name;
  cfg.agent_welcome_message = p.welcome;
  cfg.calling_guardrails = { call_start_hour: 9, call_end_hour: 21 };
  task.task_config.call_terminate = 120;
  task.task_config.call_cancellation_prompt =
    'End the call once the goal is done, or the assistant says it cannot help, and you have said thank you.';
  tools.api_tools = null;
  tools.transcriber.language = p.language;
  tools.transcriber.context = "A test caller speaks with Aero Bank's AI assistant about a card, an EMI or a fee.";
  tools.transcriber.keywords = 'Aero Bank, card, freeze, EMI, fee, waiver';
  tools.synthesizer.provider_config.language = p.language;
  agent.agent_prompts = { task_1: { system_prompt: prompt(p) } };
  writeFileSync(`agents/${p.id}.json`, `${JSON.stringify(agent, null, 2)}\n`);
  console.log(`wrote agents/${p.id}.json`);
}
